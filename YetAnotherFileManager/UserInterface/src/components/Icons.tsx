interface IconProps extends SVGProps<SVGSVGElement> {
    size?: number;
}

type SvgComponent = FC<SVGProps<SVGSVGElement>>;

/** Wraps an imported SVG so every icon keeps the shared `size` prop and inherits currentColor. */
function sized(Svg: SvgComponent, defaultSize: number): FC<IconProps> {
    return ({size = defaultSize, ...props}) => <Svg aria-hidden height={size} width={size} {...props}/>;
}

